"""
LangGraph Multi-Agent Architecture: Memory/Ontology DeepAgent + Execution DeepAgent
===================================================================================
A two-tier DeepAgent workflow implemented with LangGraph and powered by local
Subscription Reverse Proxy (`http://127.0.0.1:8000/v1`).

Architecture Overview:
----------------------
1. 🧠 DeepAgent 1 (Memory & Ontology Agent - "The Knowledge Architect"):
   - Maintains persistent knowledge graph (entities & relations) and episodic memory.
   - Phase 1 (Planning): Entity linking, context retrieval, and generates a structured Directive Contract.
   - Phase 2 (Reflection): Analyzes execution evidence, extracts new triples, updates the ontology, and synthesizes final response.

2. ⚙️ DeepAgent 2 (Execution Agent - "The Tool Operator"):
   - Receives the Directive from DeepAgent 1.
   - Dispatches and coordinates specialized subagents/tools:
     * Math & Calculation Subagent
     * Python Code Execution Subagent
     * Lab Knowledge Base Subagent
     * System & Runtime Inspection Subagent
   - Synthesizes raw execution evidence and reports back to DeepAgent 1.

3. 🔄 LangGraph State Machine:
   [START] -> memory_planner -> execution_engine -> memory_reflector -> [END]
"""

