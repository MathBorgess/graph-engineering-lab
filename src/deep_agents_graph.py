# 3. Subagent Tools for DeepAgent 2 (Execution Agent)
# ---------------------------------------------------------
class SubagentTools:
    """Specialized action tools dispatched by the Execution Agent."""

    @staticmethod
    def calculate(expression: str) -> str:
        """Evaluates mathematical expressions safely."""
        allowed = {
            "math": math,
            "abs": abs,
            "round": round,
            "min": min,
            "max": max,
            "sum": sum,
            "pow": pow,
            "sqrt": math.sqrt,
            "log": math.log,
            "pi": math.pi,
            "e": math.e,
        }
        try:
            clean = expression.strip().strip("'\"")
            # Replace ^ with ** for intuitive power operation
            clean = re.sub(r"(?<=\d|\))\s*\^\s*(?=\d|\()", " ** ", clean)
            val = eval(clean, {"__builtins__": {}}, allowed)
            return f"Result: {val}"
        except Exception as e:
            return f"Calculation error: {e}"

    @staticmethod
    def python_eval(code: str) -> str:
        """Executes a Python snippet and captures output or returned expressions."""
        import io
        import contextlib

        stdout_buf = io.StringIO()
        clean_code = code.strip().strip("`")
        if clean_code.startswith("python\n"):
            clean_code = clean_code[7:]

        local_vars: Dict[str, Any] = {"math": math, "json": json}
        try:
            with contextlib.redirect_stdout(stdout_buf):
                try:
                    expr_val = eval(clean_code, {"__builtins__": __builtins__}, local_vars)
                    if expr_val is not None:
                        print(expr_val)
                except SyntaxError:
                    exec(clean_code, {"__builtins__": __builtins__}, local_vars)
            output = stdout_buf.getvalue().strip()
            return output if output else "Execution successful (no stdout)."
        except Exception as e:
            return f"Python execution error: {e}"

    @staticmethod
    def system_inspect(query: str) -> str:
        """Inspects system runtime, OS details, Python environment, or timestamps."""
        q = query.lower()
        now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        if "time" in q or "date" in q:
            return f"Local Time: {now_str}"
        elif "python" in q:
            return f"Python {platform.python_version()} on {sys.executable}"
        elif "os" in q or "platform" in q:
            return f"OS: {platform.system()} {platform.release()} ({platform.machine()})"
        return f"System Info: {platform.system()} {platform.machine()} | Python {platform.python_version()} | Time: {now_str}"

    @staticmethod
    def lab_knowledge(query: str) -> str:
        """Queries the Graph Engineering Lab internal registry for domain topics."""
        db = {
            "graphrag": "GraphRAG uses hierarchical graph indexing (communities) to summarize and extract insights across corpora.",
            "neo4j": "Graph database using Cypher property graph model, widely used for enterprise knowledge graphs.",
            "langgraph": "Stateful graph engine with nodes, edges, checkpointing, and human-in-the-loop agent patterns.",
            "deepagents": "Multi-agent systems where high-level cognitive tasks (memory, ontology) are segregated from actuation.",
        }
        for k, v in db.items():
            if k in query.lower():
                return f"[{k.upper()}]: {v}"
        return f"No specialized lab entry for '{query}'. Available entries: {', '.join(db.keys())}"


# ---------------------------------------------------------
# Helper: Robust JSON Extractor
# ---------------------------------------------------------
def extract_json(raw_text: str) -> Dict[str, Any]:
    """Safely extracts JSON even if surrounded by markdown code blocks or conversational text."""
    clean = raw_text.strip()
    if clean.startswith("```"):
        lines = clean.splitlines()
        if lines[0].startswith("```"):
            lines = lines[1:]
        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]
        clean = "\n".join(lines).strip()

    try:
        return json.loads(clean)
    except json.JSONDecodeError:
        match = re.search(r"\{.*\}", clean, re.DOTALL)
        if match:
            return json.loads(match.group(0))
        raise ValueError(f"Could not parse valid JSON from text: {raw_text[:200]}...")


