# 4. DeepAgents LangGraph Workflow Class
# ---------------------------------------------------------
class DeepAgentsWorkflow:
    """Encapsulates the multi-agent cognitive architecture and LangGraph graph."""

    def __init__(self, llm: ChatOpenAI):
        self.llm = llm

    def memory_plan_node(self, state: DeepAgentState) -> Dict[str, Any]:
        """
        DeepAgent 1 (The Architect - Phase 1):
        - Analyzes user goal and retrieves relevant context from active ontology.
        - Produces a formal Directive Contract for DeepAgent 2.
        """
        user_goal = state["user_goal"]
        ontology = state["ontology"]
        memory = state.get("memory", {})

        print("\n" + "═" * 75)
        print("🧠 [DeepAgent 1: Memory & Ontology Agent] -> PHASE 1: PLANNING & CONTEXT RETRIEVAL")
        print("═" * 75)

        prompt = f"""You are DeepAgent 1 (The Memory & Ontology Architect) in a multi-agent system.
Your mission is to analyze the user goal, consult the current domain ontology, and formulate a precise Directive Contract for DeepAgent 2 (The Execution Agent).

CURRENT ONTOLOGY ENTITIES:
{json.dumps(list(ontology['entities'].keys()), indent=2)}

CURRENT ONTOLOGY TRIPLES:
{json.dumps(ontology['triples'], indent=2)}

PAST EPISODIC MEMORY:
{json.dumps(memory.get('episodic', []), indent=2)}

USER GOAL:
"{user_goal}"

Respond with ONLY a JSON object formatted as:
{{
  "identified_concepts": ["list of entities relevant to this goal"],
  "ontology_context_summary": "brief summary of relevant relationships already known",
  "execution_objective": "concise, unambiguous instruction for the execution agent",
  "required_tool_actions": ["list of tools/subagents that should be used, e.g. calculate, python_eval, system_inspect, lab_knowledge"],
  "constraints": ["rules the execution agent must adhere to"]
}}"""

        response = self.llm.invoke([
            SystemMessage(content="You are an expert Ontology Architect. Output ONLY valid JSON."),
            HumanMessage(content=prompt),
        ])

        try:
            plan_data = extract_json(response.content)
        except Exception as e:
            logger.warning(f"Fallback plan parsing: {e}")
            plan_data = {
                "identified_concepts": [],
                "ontology_context_summary": "Domain query analysis",
                "execution_objective": user_goal,
                "required_tool_actions": ["calculate", "python_eval"],
                "constraints": ["Provide exact numbers and evidence"],
            }

        print(f"📌 Identified Concepts : {plan_data.get('identified_concepts')}")
        print(f"🎯 Execution Objective : {plan_data.get('execution_objective')}")
        print(f"🛠️  Required Subagents  : {plan_data.get('required_tool_actions')}")

        directive = {
            "objective": plan_data.get("execution_objective", user_goal),
            "target_tools": plan_data.get("required_tool_actions", []),
            "constraints": plan_data.get("constraints", []),
            "domain_hints": plan_data.get("ontology_context_summary", ""),
            "timestamp": datetime.datetime.now().isoformat(),
        }

        return {
            "directive": directive,
            "execution_trace": [f"[MemoryAgent] Formulated Directive: {directive['objective']}"],
        }

    def execution_engine_node(self, state: DeepAgentState) -> Dict[str, Any]:
        """
        DeepAgent 2 (The Operator):
        - Dispatches subagent tools according to the Directive.
        - Compiles observations and reports findings.
        """
        directive = state["directive"]
        user_goal = state["user_goal"]

        print("\n" + "─" * 75)
        print("⚙️  [DeepAgent 2: Execution Agent] -> EXECUTING DIRECTIVE CONTRACT")
        print("─" * 75)
        print(f"📥 Received Directive: {directive['objective']}")

        tools_manifest = """
Available Subagents/Tools:
1. calculate(expression: str) -> Safe arithmetic evaluation (e.g. '15000 * 128 / (1024 * 1024)')
2. python_eval(code: str) -> Run arbitrary Python algorithms, graph math, data transformations
3. system_inspect(query: str) -> Check runtime OS, Python version, local time
4. lab_knowledge(query: str) -> Query Graph Engineering Lab definitions (GraphRAG, Neo4j, etc.)
"""

        prompt = f"""You are DeepAgent 2 (The Execution Agent).
You received the following Directive from DeepAgent 1 (The Memory & Ontology Architect):

DIRECTIVE:
"{directive['objective']}"

ORIGINAL USER GOAL:
"{user_goal}"

CONSTRAINTS:
{json.dumps(directive.get('constraints', []), indent=2)}

{tools_manifest}

Plan and execute the required subagent actions.
Output ONLY a JSON list of tool invocations to run:
[
  {{"tool": "calculate" | "python_eval" | "system_inspect" | "lab_knowledge", "input": "argument string"}}
]"""

        response = self.llm.invoke([
            SystemMessage(content="You are a precise execution agent. Output ONLY a valid JSON list."),
            HumanMessage(content=prompt),
        ])

        tool_calls = []
        try:
            raw_clean = response.content.strip()
            if raw_clean.startswith("```"):
                lines = raw_clean.splitlines()
                if lines[0].startswith("```"):
                    lines = lines[1:]
                if lines and lines[-1].strip() == "```":
                    lines = lines[:-1]
                raw_clean = "\n".join(lines).strip()
            parsed = json.loads(raw_clean)
            if isinstance(parsed, list):
                tool_calls = parsed
            elif isinstance(parsed, dict) and "tool" in parsed:
                tool_calls = [parsed]
        except Exception as e:
            logger.warning(f"Error parsing tool calls: {e}")

        trace = list(state.get("execution_trace", []))
        observations = []

        for call in tool_calls:
            t_name = call.get("tool", "")
            t_input = str(call.get("input", ""))
            print(f"🔧 Invoking Subagent [{t_name}] with input: {t_input}")

            if t_name == "calculate":
                res = SubagentTools.calculate(t_input)
            elif t_name == "python_eval":
                res = SubagentTools.python_eval(t_input)
            elif t_name == "system_inspect":
                res = SubagentTools.system_inspect(t_input)
            elif t_name == "lab_knowledge":
                res = SubagentTools.lab_knowledge(t_input)
            else:
                res = f"Unknown tool '{t_name}'"

            print(f"   ↳ Observation: {res}")
            observations.append({"tool": t_name, "input": t_input, "output": res})
            trace.append(f"[ExecAgent:{t_name}] In: {t_input} -> Out: {res}")

        # Synthesize findings
        synthesis_prompt = f"""You are DeepAgent 2. You have executed tools for the Directive: "{directive['objective']}".

OBSERVATIONS & EVIDENCE:
{json.dumps(observations, indent=2)}

Summarize your findings in a structured JSON report:
{{
  "evidence_summary": "detailed explanation of findings with factual data",
  "derived_facts": ["list of concrete, atomic statements or facts discovered"],
  "status": "completed"
}}"""

        synth_resp = self.llm.invoke([
            SystemMessage(content="Output ONLY valid JSON report."),
            HumanMessage(content=synthesis_prompt),
        ])

        try:
            report = extract_json(synth_resp.content)
        except Exception:
            report = {
                "evidence_summary": "\n".join(f"{o['tool']}: {o['output']}" for o in observations),
                "derived_facts": [str(o["output"]) for o in observations],
                "status": "completed",
            }

        return {
            "execution_result": report,
            "execution_trace": trace,
            "iteration_count": state.get("iteration_count", 0) + 1,
        }

    def memory_reflect_node(self, state: DeepAgentState) -> Dict[str, Any]:
        """
        DeepAgent 1 (The Architect - Phase 2):
        - Ingests empirical observations from DeepAgent 2.
        - Discovers new entities and relationship triples.
        - Mutates the Knowledge Graph ontology.
        - Records episodic lessons and delivers final response.
        """
        user_goal = state["user_goal"]
        ontology = dict(state["ontology"])
        memory = dict(state.get("memory", {}))
        execution_result = state["execution_result"]

        print("\n" + "═" * 75)
        print("🧠 [DeepAgent 1: Memory & Ontology Agent] -> PHASE 2: REFLECTION & ONTOLOGY EVOLUTION")
        print("═" * 75)

        prompt = f"""You are DeepAgent 1 (The Memory & Ontology Architect).
The Execution Agent has completed its mission and reported empirical evidence.
Your task is to:
1. Synthesize the final comprehensive answer for the user.
2. Extract new entities and Knowledge Graph triples (Subject - Predicate - Object) discovered during this task.
3. Formulate an episodic memory entry summarizing what was learned.

USER GOAL:
"{user_goal}"

EXECUTION EVIDENCE & FACTS:
{json.dumps(execution_result, indent=2)}

EXISTING ONTOLOGY TRIPLES:
{json.dumps(ontology.get('triples', []), indent=2)}

Respond with ONLY a JSON object:
{{
  "final_answer": "Complete, structured, and polished final answer to the user goal",
  "new_entities": [
    {{"name": "...", "type": "...", "description": "..."}}
  ],
  "new_triples": [
    {{"subject": "...", "predicate": "...", "object": "..."}}
  ],
  "episodic_lesson": "Brief lesson learned or decision captured for long-term memory"
}}"""

        response = self.llm.invoke([
            SystemMessage(content="You are an expert Ontology Architect. Output ONLY valid JSON."),
            HumanMessage(content=prompt),
        ])

        try:
            reflection_data = extract_json(response.content)
        except Exception as e:
            logger.warning(f"Error parsing reflection JSON: {e}")
            reflection_data = {
                "final_answer": execution_result.get("evidence_summary", "Task executed."),
                "new_entities": [],
                "new_triples": [],
                "episodic_lesson": f"Executed goal: {user_goal}",
            }

        # Update Ontology Entities
        for ent in reflection_data.get("new_entities", []):
            name = ent.get("name")
            if name and name not in ontology["entities"]:
                ontology["entities"][name] = {
                    "name": name,
                    "type": ent.get("type", "Entity"),
                    "description": ent.get("description", ""),
                    "attributes": {"discovered_at": datetime.datetime.now().isoformat()},
                }
                print(f"✨ [Ontology Growth] Added Entity: {name} ({ent.get('type')})")

        # Update Ontology Triples
        existing_triple_keys = {
            (t["subject"].lower(), t["predicate"].lower(), t["object"].lower())
            for t in ontology.get("triples", [])
        }

        added_triples = []
        for trip in reflection_data.get("new_triples", []):
            s, p, o = trip.get("subject", ""), trip.get("predicate", ""), trip.get("object", "")
            if s and p and o:
                key = (s.lower(), p.lower(), o.lower())
                if key not in existing_triple_keys:
                    triple_obj = {"subject": s, "predicate": p, "object": o}
                    ontology["triples"].append(triple_obj)
                    existing_triple_keys.add(key)
                    added_triples.append(triple_obj)
                    print(f"🔗 [Ontology Growth] Added Triple: ({s}) ──[:{p}]──> ({o})")

        # Update Episodic Memory
        episodic_list = list(memory.get("episodic", []))
        episodic_list.append({
            "goal": user_goal,
            "lesson": reflection_data.get("episodic_lesson", ""),
            "timestamp": datetime.datetime.now().isoformat(),
            "triples_added": len(added_triples),
        })
        memory["episodic"] = episodic_list

        final_answer = reflection_data.get("final_answer", "")

        return {
            "ontology": ontology,
            "memory": memory,
            "reflection": reflection_data,
            "final_output": final_answer,
        }

    def compile_graph(self):
        """Builds and compiles the LangGraph StateGraph."""
        workflow = StateGraph(DeepAgentState)

        workflow.add_node("memory_planner", self.memory_plan_node)
        workflow.add_node("execution_engine", self.execution_engine_node)
        workflow.add_node("memory_reflector", self.memory_reflect_node)

        workflow.add_edge(START, "memory_planner")
        workflow.add_edge("memory_planner", "execution_engine")
        workflow.add_edge("execution_engine", "memory_reflector")
        workflow.add_edge("memory_reflector", END)

        return workflow.compile()


