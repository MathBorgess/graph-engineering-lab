def run_goal(app, goal: str, initial_ontology: Optional[Dict[str, Any]] = None):
    """Executes a single user goal through the compiled LangGraph workflow."""
    ontology = initial_ontology or create_initial_ontology()

    initial_state: DeepAgentState = {
        "messages": [HumanMessage(content=goal)],
        "user_goal": goal,
        "ontology": ontology,
        "memory": {"episodic": [], "working": {}},
        "directive": {},
        "execution_trace": [],
        "execution_result": {},
        "reflection": {},
        "final_output": "",
        "iteration_count": 0,
    }

    print("\n" + "★" * 75)
    print(f"🚀 INITIATING DEEPAGENTS WORKFLOW FOR GOAL:\n   \"{goal}\"")
    print("★" * 75)

    result_state = app.invoke(initial_state)

    print("\n" + "═" * 75)
    print("💡 FINAL ANSWER DELIVERED BY DEEPAGENT 1:")
    print("═" * 75)
    print(result_state["final_output"])
    print("═" * 75)

    display_ontology_graph(result_state["ontology"])
    return result_state


def main():
    parser = argparse.ArgumentParser(description="DeepAgents LangGraph Multi-Agent Workflow")
    parser.add_argument("--endpoint", default="http://127.0.0.1:8000/v1", help="Subscription Proxy URL")
    parser.add_argument("--model", default="codex", choices=["codex", "claude", "gpt-6-sol", "claude-haiku-4-5-20251001"])
    parser.add_argument("--query", type=str, default=None, help="Single query to run")
    parser.add_argument("--test", action="store_true", help="Run multi-step study benchmark")
    parser.add_argument("--mermaid", action="store_true", help="Print Mermaid flowchart diagram")
    args = parser.parse_args()

    if args.mermaid:
        print_mermaid()
        return

    print("=" * 70)
    print("🤖 Compiling DeepAgents LangGraph Workflow...")
    print(f"   LLM Proxy Endpoint : {args.endpoint}")
    print(f"   Selected Model     : {args.model}")
    print("=" * 70)

    llm = ChatOpenAI(
        base_url=args.endpoint,
        api_key="subscription-proxy",
        model=args.model,
        temperature=0.0,
        use_responses_api=False,
    )

    workflow_mgr = DeepAgentsWorkflow(llm=llm)
    app = workflow_mgr.compile_graph()

    if args.test:
        test_goal = (
            "Analyze GraphRAG within our Graph Engineering Lab. Calculate the memory required for 15,000 "
            "entities if each node record takes 128 bytes, convert to megabytes (divide by 1024 * 1024), "
            "and check our runtime OS and local time."
        )
        run_goal(app, test_goal)
        return

    if args.query:
        run_goal(app, args.query)
        return

    # Interactive Studio Loop
    ontology = create_initial_ontology()
    print("\n" + "=" * 65)
