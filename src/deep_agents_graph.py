    print("├" + "─" * 70 + "┤")
    print(f"│ Entities ({len(ontology['entities'])}):")
    for k, v in ontology["entities"].items():
        desc = v.get("description", "")
        if len(desc) > 36:
            desc = desc[:33] + "..."
