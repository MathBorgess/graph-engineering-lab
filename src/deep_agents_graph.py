    print("│")
    print(f"│ Semantic Triples ({len(ontology['triples'])}):")
    for t in ontology["triples"]:
        print(f"│   • ({t['subject']}) ──[:{t['predicate']}]──> ({t['object']})")
    print("└" + "─" * 70 + "┘\n")


